export interface ParagraphBlock {
  kind: 'paragraph';
  text: string;
}

export interface StepItem {
  /** 步骤标题（动宾短语，如「打开设置」）。 */
  title: string;
  /** 步骤说明：在哪、点什么、会发生什么。 */
  desc: string;
}

export interface StepsBlock {
  kind: 'steps';
  items: StepItem[];
}

export interface ImageBlock {
  kind: 'image';
  /** 相对 public 的路径，如 screenshots/guide-model-config.png。 */
  src: string;
  alt: string;
  caption?: string;
  /** 图片实际像素尺寸：img 尺寸预留，防懒加载时布局偏移（CLS）。截图采集时填实际值。 */
  width?: number;
  height?: number;
}

export interface TipBlock {
  kind: 'tip';
  text: string;
}

export interface LinkItem {
  label: string;
  href: string;
  /** true = 新标签页打开外部网站。 */
  external?: boolean;
}

export interface LinksBlock {
  kind: 'links';
  items: LinkItem[];
}

export type ManualBlock = ParagraphBlock | StepsBlock | ImageBlock | TipBlock | LinksBlock;

export interface ManualSection {
  /** 锚点 id，访问形态 guide.html#<id>。kebab-case。 */
  id: string;
  title: string;
  blocks: ManualBlock[];
}

export interface ManualPart {
  /** 板块锚点 id。 */
  id: string;
  title: string;
  intro: string;
  sections: ManualSection[];
}

